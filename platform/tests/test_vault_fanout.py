"""The vault HOST's exporter as the only writer for a shared Google account.

One vault id is one Google account and one browser family (see
gen-conf `vault_hosts`), so the family runs on the host partition while every
member's apps keep reading their OWN `COOKIES_FILE`. That makes the exporter's
writes a fan-out, and the rules that matter are:

- a jar is fanned out only after the host accepted it, and the per-path
  external-write hold-off still applies (a member's in-flight yt-dlp write-back
  is not clobbered);
- the state file is mirrored unconditionally, because no consumer ever writes
  it and it is the file each member's watchdog judges liveness from;
- a member whose paths are unwritable must not take the host's export down;
- startup publishes what the FILE says, not a blind `unknown` (only `down`
  arms auto_signin, and a vault that just gained its first browser has a file
  that was never exported).

`cookie_exporter.py` lives in stack/vault (the ytcookies exporter, vendored):
importing it needs websocket-client, which only the image has, so this whole
module skips on a host without it. The functions under test touch no browser
and no network.
"""
import json
import os
import time

import pytest

pytest.importorskip("websocket")

import sys

BASE = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
# Two homes, one layout difference: the repo keeps the vendored exporter under
# `stack/vault`, while the image flattens `stack/*` to the top of /srv/stack
# (Dockerfile `COPY stack/vault ./vault`). Both are searched so the suite says
# the same thing on a host checkout and inside the image.
for _cand in (os.path.join(BASE, "stack", "vault"),
              os.path.join(BASE, "vault")):
    if os.path.isdir(_cand):
        VAULT_DIR = _cand
        break
else:
    VAULT_DIR = os.path.join(BASE, "stack", "vault")   # the skip message names it
if VAULT_DIR not in sys.path:
    sys.path.insert(0, VAULT_DIR)

import cookie_exporter as ce  # noqa: E402

JAR = ("# Netscape HTTP Cookie File\n"
       "# https://curl.se/docs/http-cookies.html\n"
       "# This file was generated by ytcookies. Do not edit.\n"
       "\n"
       ".youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\thotpotato\n")

COOKIES = [{"name": "SID", "value": "hotpotato", "domain": ".youtube.com",
            "path": "/", "secure": True, "expirationDate": "2000000000"}]


@pytest.fixture
def vault(tmp_path, monkeypatch):
    """The exporter pointed at a host + two member partition homes under one
    tmpdir, with every path/limit it froze at import time repointed."""
    data = tmp_path / "data"
    home = data / "users/owner"
    home.mkdir(parents=True)
    members = [data / f"users/{s}" for s in ("family", "kid")]
    for d in members:
        d.mkdir(parents=True)
    monkeypatch.setattr(ce, "OUT_PATH", str(home / "cookies.txt"))
    monkeypatch.setattr(ce, "SESSION_STATE_PATH", str(home / "session-state.json"))
    monkeypatch.setattr(ce, "COOKIE_FANOUT_FILES",
                        [str(d / "cookies.txt") for d in members])
    monkeypatch.setattr(ce, "COOKIE_SESSION_STATE_FANOUT",
                        [str(d / "session-state.json") for d in members])
    monkeypatch.setattr(ce, "EXTERNAL_WRITE_COOLDOWN", 120)
    return {"data": data, "home": home, "members": members}


def jar_of(path):
    return open(path, encoding="utf-8").read()


# ---------------------------------------------------------------------- jar
def test_the_accepted_jar_lands_in_every_member_home(vault, monkeypatch):
    """Without this, a member's cookies age out with no browser of its own to
    refresh them: the dedup removed its chromium, and nothing else writes its
    jar. The bytes are identical because a jar is not rewritten per tenant."""
    monkeypatch.setattr(ce, "to_netscape", lambda cookies: JAR)
    assert ce._export_if_ok(COOKIES, "seed") is True
    host_jar = jar_of(vault["home"] / "cookies.txt")
    assert host_jar == JAR
    for d in vault["members"]:
        assert jar_of(d / "cookies.txt") == host_jar


def test_a_member_written_from_outside_is_left_alone_for_the_cooldown(vault,
                                                                      monkeypatch):
    """A member's own yt-dlp run writes its jar back. Fanning over that within
    the hold-off window throws away cookies the consumer just learned about -
    the same reason the host's own write holds off."""
    monkeypatch.setattr(ce, "to_netscape", lambda cookies: JAR)
    member = vault["members"][0] / "cookies.txt"
    member.write_text("# from yt-dlp write-back\n")
    old = os.stat(member).st_mtime
    assert ce._export_if_ok(COOKIES, "seed") is True
    assert jar_of(member) == "# from yt-dlp write-back\n"
    assert os.stat(member).st_mtime == old
    # The other member, untouched, still gets it: one busy consumer does not
    # stall the fan-out for the rest.
    assert jar_of(vault["members"][1] / "cookies.txt") == JAR


def test_the_fan_out_waits_for_the_host_to_accept_the_jar(vault, monkeypatch):
    """The hold-off on the HOST's file is a reason not to export at all; fanning
    the refused text out anyway would put a jar nobody verified into every
    member's home, and their next yt-dlp run would write it back as truth."""
    monkeypatch.setattr(ce, "to_netscape", lambda cookies: JAR)
    (vault["home"] / "cookies.txt").write_text("# externally written\n")
    assert ce._export_if_ok(COOKIES, "seed") is False
    assert jar_of(vault["home"] / "cookies.txt") == "# externally written\n"
    for d in vault["members"]:
        assert not (d / "cookies.txt").exists()


def test_one_member_that_cannot_be_written_does_not_stop_the_other_one(vault,
                                                                       monkeypatch):
    """A member directory can legitimately be missing (a partition added on the
    host side whose home a create-failure never made, a mount that went away).
    The host's own export is the thing that must survive, and so must the other
    members' copies."""
    monkeypatch.setattr(ce, "to_netscape", lambda cookies: JAR)
    gone = vault["members"][0]
    gone.rmdir()
    assert ce._export_if_ok(COOKIES, "seed") is True
    assert jar_of(vault["home"] / "cookies.txt") == JAR
    assert jar_of(vault["members"][1] / "cookies.txt") == JAR


def test_the_fan_out_never_touches_the_host_paths_it_was_given_twice(vault,
                                                                     monkeypatch):
    """The host's own jar is written by the primary path. If its path were also
    in the list, a member's external write-back and the host's own write would
    fight over one file and the hold-off would report the host's own write as
    external churn."""
    keys = [ce.OUT_PATH] + ce.COOKIE_FANOUT_FILES
    assert len(keys) == len(set(keys))
    assert vault["home"] / "cookies.txt" not in [
        __import__("pathlib").Path(p) for p in ce.COOKIE_FANOUT_FILES]


# ---------------------------------------------------------------- state file
def test_the_state_report_is_mirrored_to_every_member(vault):
    """No consumer ever writes session-state.json, so it is the one file whose
    mirroring cannot wait for a cooldown: a frozen mtime is how a dead exporter
    is detected, so a member whose browser was deduped away has to keep getting
    the host's report or its watchdog would demand a chromium forever."""
    ce.write_session_state("up")
    host = json.loads((vault["home"] / "session-state.json").read_text())
    assert host["state"] == "up"
    for d in vault["members"]:
        payload = json.loads((d / "session-state.json").read_text())
        assert payload["state"] == "up"
        assert abs(payload["ts"] - host["ts"]) <= 2


def test_state_mirroring_survives_a_member_that_cannot_be_written(vault):
    """The host's own state write is what its watchdog reads; a member that
    fails must not abort the loop before the rest of them are told."""
    gone = vault["members"][0] / "session-state.json"
    vault["members"][0].rmdir()
    ce.write_session_state("down")
    assert json.loads(
        (vault["home"] / "session-state.json").read_text())["state"] == "down"
    assert json.loads(
        (vault["members"][1] / "session-state.json").read_text())["state"] == "down"
    assert not gone.exists()


def test_a_state_write_failure_is_reported_not_raised(vault, monkeypatch):
    """Every partition's apps keep listening while the fan-out is broken; a
    member on a read-only mount has to be a log line, not a dead exporter (and
    a dead exporter is a member whose session never comes back)."""
    seen = []
    real = ce.atomic_write
    def selective(path, content):
        if "family" in path:
            raise OSError(30, "Read-only file system")
        real(path, content)
    monkeypatch.setattr(ce, "log", seen.append)
    monkeypatch.setattr(ce, "atomic_write", selective)
    ce.write_session_state("up")
    assert json.loads(
        (vault["home"] / "session-state.json").read_text())["state"] == "up"
    assert json.loads(
        (vault["members"][1] / "session-state.json").read_text())["state"] == "up"
    assert any("family" in m for m in seen), seen


# ------------------------------------------------------------- bootstrap state
@pytest.fixture
def no_network(monkeypatch):
    """probe_file/file_cookie_header are the only two sources of evidence
    bootstrap_state has; the probe itself is a live HTTPS GET."""
    def _set(alive, header):
        monkeypatch.setattr(ce, "probe_file", lambda: alive)
        monkeypatch.setattr(ce, "file_cookie_header", lambda: header)
    return _set


def test_a_file_the_server_accepts_boots_as_up(no_network):
    """A restarted exporter on a live vault must not advertise `unknown`:
    the watchdog would start a browser for a session that is working."""
    no_network(True, "SID=x")
    assert ce.bootstrap_state() == "up"


def test_a_file_the_server_bounces_boots_as_down(no_network):
    no_network(False, "SID=x")
    assert ce.bootstrap_state() == "down"


def test_a_never_exported_file_boots_as_down(no_network):
    """The case a new partition's first browser hits: nothing to probe, so a
    blind `unknown` would leave nobody arming auto_signin and no one typing the
    password while a chromium sits idle."""
    no_network(None, None)
    assert ce.bootstrap_state() == "down"


def test_an_unanswerable_probe_stays_unknown(no_network):
    """Cookies that the probe could not judge (network down) are NOT evidence
    of death: declaring `down` would stage a sign-in and burn a session that is
    probably fine."""
    no_network(None, "SID=x")
    assert ce.bootstrap_state() == "unknown"


def test_no_fan_out_lists_means_the_original_single_file_behaviour(tmp_path,
                                                                  monkeypatch):
    """The standalone deployment (ytcookies alone, and any vault with no
    members) leaves both lists unset. Nothing may depend on them being present,
    or that deployment loses its jar writes."""
    home = tmp_path / "cookies-home"
    home.mkdir()
    monkeypatch.setattr(ce, "OUT_PATH", str(home / "cookies.txt"))
    monkeypatch.setattr(ce, "SESSION_STATE_PATH", str(home / "session-state.json"))
    monkeypatch.setattr(ce, "COOKIE_FANOUT_FILES", [])
    monkeypatch.setattr(ce, "COOKIE_SESSION_STATE_FANOUT", [])
    monkeypatch.setattr(ce, "to_netscape", lambda cookies: JAR)
    assert ce._export_if_ok(COOKIES, "seed") is True
    assert jar_of(home / "cookies.txt") == JAR
    ce.write_session_state("up")
    assert json.loads(
        (home / "session-state.json").read_text())["state"] == "up"
    assert sorted(p.name for p in home.iterdir()) == [
        "cookies.txt", "session-state.json"]
